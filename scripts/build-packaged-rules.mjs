import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const require = createRequire(import.meta.url);

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const engineBundle = resolve(root, 'scripts/.engine-bundle.cjs');
buildSync({
  entryPoints: [resolve(root, 'scripts/engine-entry.ts')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  outfile: engineBundle,
  logLevel: 'silent',
});

const { parseList, compileRules, hostBucketToCss } = require(engineBundle);

const thirdPartyPath = resolve(root, 'third-party-rules.txt');

function loadRules(listPaths) {
  const allRules = [];
  for (const { path, strict } of listPaths) {
    if (!existsSync(path)) {
      if (strict) {
        console.error(`Missing required list: ${path}`);
        process.exit(1);
      }
      continue;
    }
    const { rules, errors } = parseList(readFileSync(path, 'utf8'));
    allRules.push(...rules);
    if (errors.length > 0) {
      const label = path.split(/[/\\]/).pop();
      if (strict) {
        console.error(`Parse errors in ${label}:`, errors.slice(0, 20));
        process.exit(1);
      }
      console.warn(
        `Skipped ${errors.length} unparsable line(s) in ${label} (third-party / extended syntax)`,
      );
    }
  }
  return allRules;
}

const darklistRules = loadRules([{ path: resolve(root, 'lists/darklist.txt'), strict: true }]);
const fixtureRules = loadRules([{ path: resolve(root, 'lists/e2e-fixture.txt'), strict: true }]);
const thirdPartyRules = loadRules([{ path: thirdPartyPath, strict: false }]);

if (darklistRules.length === 0) {
  console.error('No rules compiled — check lists/darklist.txt');
  process.exit(1);
}

const bootCompiled = compileRules([...darklistRules, ...fixtureRules]);
const darklistCompiled = compileRules(darklistRules);
const fixtureCompiled = compileRules(fixtureRules);
const thirdCompiled = compileRules(thirdPartyRules);
if (bootCompiled.errors.length > 0 || darklistCompiled.errors.length > 0 || fixtureCompiled.errors.length > 0) {
  console.error(
    'Parse/compile errors in boot lists:',
    [...bootCompiled.errors, ...darklistCompiled.errors, ...fixtureCompiled.errors].slice(0, 20),
  );
  process.exit(1);
}
if (thirdCompiled.errors.length > 0) {
  console.warn(
    `Compile skipped ${thirdCompiled.errors.length} third-party rule(s) (validation / unsupported operators)`,
  );
}

writeFileSync(resolve(root, 'cosmetic-boot.css'), bootCompiled.genericCss, 'utf8');

mkdirSync(resolve(root, 'dist'), { recursive: true });

const hostCss = {};
for (const [host, bucket] of thirdCompiled.hostBuckets) {
  const css = hostBucketToCss(host, bucket);
  if (css) {
    hostCss[host] = css;
  }
}
writeFileSync(
  resolve(root, 'dist/packaged-host-css.json'),
  JSON.stringify(hostCss),
  'utf8',
);

const procedural = [];
const seenProc = new Set();

function collectProcedural(compiled, list) {
  for (const bucket of compiled.hostBuckets.values()) {
    for (const rule of bucket.procedural) {
      if (seenProc.has(rule.ruleId)) {
        continue;
      }
      seenProc.add(rule.ruleId);
      procedural.push({ rule, list });
    }
  }
}

collectProcedural(darklistCompiled, 'darklist');
collectProcedural(fixtureCompiled, 'e2e-fixture');
collectProcedural(thirdCompiled, 'third-party');

function serRegex(re) {
  return { source: re.source, flags: re.flags };
}

function serValue(v) {
  return v instanceof RegExp ? serRegex(v) : v;
}

const serialized = procedural.map(({ rule, list }) => ({
  list,
  ruleId: rule.ruleId,
  hosts: rule.hosts,
  entity: rule.entity,
  pathRe: rule.pathRe ? serRegex(rule.pathRe) : null,
  selector: rule.selector,
  procedural: rule.procedural.map((op) => {
    switch (op.type) {
      case 'has-text':
        return { type: op.type, needle: serValue(op.needle) };
      case 'matches-path':
        return { type: op.type, pattern: serValue(op.pattern) };
      case 'matches-attr':
        return {
          type: op.type,
          name: op.name,
          value: op.value === undefined ? undefined : serValue(op.value),
        };
      case 'matches-css':
        return {
          type: op.type,
          property: op.property,
          value: serValue(op.value),
        };
      default:
        return op;
    }
  }),
  action:
    rule.action.type === 'remove-attr' || rule.action.type === 'remove-class'
      ? { ...rule.action, pattern: serValue(rule.action.pattern) }
      : rule.action,
}));

const subscriptions = JSON.parse(
  readFileSync(resolve(root, 'src/background/subscriptions.json'), 'utf8'),
);

const out = `import type { CompiledProc } from '../engine/types.js';
import { reviveCompiledProc, type StoredCompiledProc } from '../engine/serialized.js';

/** Generated by \`npm run build\` — do not edit by hand. */
export const PACKAGED_REV = ${JSON.stringify(subscriptions.packagedRev)};

export type PackagedList = 'darklist' | 'e2e-fixture' | 'third-party';

export interface PackagedRule {
  rule: CompiledProc;
  list: PackagedList;
}

const SERIALIZED = ${JSON.stringify(serialized, null, 2)} as const;

export function revivePackagedRules(): PackagedRule[] {
  return (SERIALIZED as unknown as Array<StoredCompiledProc & { list: PackagedList }>).map((row) => ({
    list: row.list,
    rule: reviveCompiledProc(row),
  }));
}
`;

writeFileSync(resolve(root, 'src/content/packaged-rules.ts'), out, 'utf8');
console.log(
  `Wrote cosmetic-boot.css (${bootCompiled.genericCss.length} bytes), dist/packaged-host-css.json (${Object.keys(hostCss).length} hosts), ${procedural.length} procedural rules`,
);
