import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const require = createRequire(import.meta.url);

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const engineBundle = resolve(root, 'scripts/.engine-bundle.cjs');
buildSync({
  entryPoints: [resolve(root, 'scripts/engine-entry.ts')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  outfile: engineBundle,
  logLevel: 'silent',
});

const { parseList, compileRules, hostBucketToCss } = require(engineBundle);

const bootListPaths = [
  { path: resolve(root, 'lists/darklist.txt'), strict: true },
  { path: resolve(root, 'lists/e2e-fixture.txt'), strict: true },
];
const thirdPartyPath = resolve(root, 'third-party-rules.txt');

function loadRules(listPaths) {
  const allRules = [];
  for (const { path, strict } of listPaths) {
    if (!existsSync(path)) {
      if (strict) {
        console.error(`Missing required list: ${path}`);
        process.exit(1);
      }
      continue;
    }
    const { rules, errors } = parseList(readFileSync(path, 'utf8'));
    allRules.push(...rules);
    if (errors.length > 0) {
      const label = path.split(/[/\\]/).pop();
      if (strict) {
        console.error(`Parse errors in ${label}:`, errors.slice(0, 20));
        process.exit(1);
      }
      console.warn(
        `Skipped ${errors.length} unparsable line(s) in ${label} (third-party / extended syntax)`,
      );
    }
  }
  return allRules;
}

const bootRules = loadRules(bootListPaths);
const thirdPartyRules = loadRules([{ path: thirdPartyPath, strict: false }]);

if (bootRules.length === 0) {
  console.error('No rules compiled — check lists/darklist.txt');
  process.exit(1);
}

const bootCompiled = compileRules(bootRules);
const thirdCompiled = compileRules(thirdPartyRules);
if (bootCompiled.errors.length > 0) {
  console.error('Parse/compile errors in boot lists:', bootCompiled.errors.slice(0, 20));
  process.exit(1);
}
if (thirdCompiled.errors.length > 0) {
  console.warn(
    `Compile skipped ${thirdCompiled.errors.length} third-party rule(s) (validation / unsupported operators)`,
  );
}

writeFileSync(resolve(root, 'cosmetic-boot.css'), bootCompiled.genericCss, 'utf8');

mkdirSync(resolve(root, 'dist'), { recursive: true });

const hostCss = {};
for (const [host, bucket] of thirdCompiled.hostBuckets) {
  const css = hostBucketToCss(host, bucket);
  if (css) {
    hostCss[host] = css;
  }
}
writeFileSync(
  resolve(root, 'dist/packaged-host-css.json'),
  JSON.stringify(hostCss),
  'utf8',
);

const procedural = [];
const seenProc = new Set();
for (const compiled of [bootCompiled, thirdCompiled]) {
  for (const bucket of compiled.hostBuckets.values()) {
    for (const rule of bucket.procedural) {
      if (seenProc.has(rule.ruleId)) {
        continue;
      }
      seenProc.add(rule.ruleId);
      procedural.push(rule);
    }
  }
}

function serRegex(re) {
  return { source: re.source, flags: re.flags };
}

function serValue(v) {
  return v instanceof RegExp ? serRegex(v) : v;
}

const serialized = procedural.map((rule) => ({
  ruleId: rule.ruleId,
  hosts: rule.hosts,
  entity: rule.entity,
  pathRe: rule.pathRe ? serRegex(rule.pathRe) : null,
  selector: rule.selector,
  procedural: rule.procedural.map((op) => {
    switch (op.type) {
      case 'has-text':
        return { type: op.type, needle: serValue(op.needle) };
      case 'matches-path':
        return { type: op.type, pattern: serValue(op.pattern) };
      case 'matches-attr':
        return {
          type: op.type,
          name: op.name,
          value: op.value === undefined ? undefined : serValue(op.value),
        };
      case 'matches-css':
        return {
          type: op.type,
          property: op.property,
          value: serValue(op.value),
        };
      default:
        return op;
    }
  }),
  action:
    rule.action.type === 'remove-attr' || rule.action.type === 'remove-class'
      ? { ...rule.action, pattern: serValue(rule.action.pattern) }
      : rule.action,
}));

const out = `import type { CompiledProc, ProcOp } from '../engine/types.js';

/** Generated by \`npm run build\` — do not edit by hand. */
const SERIALIZED = ${JSON.stringify(serialized, null, 2)} as const;

interface SerializedRegex {
  source: string;
  flags: string;
}

type SerializedProcOp =
  | { type: 'has-text'; needle: string | SerializedRegex }
  | { type: 'matches-path'; pattern: string | SerializedRegex }
  | { type: 'matches-attr'; name: string; value?: string | SerializedRegex }
  | { type: 'matches-css'; property: string; value: string | SerializedRegex }
  | { type: 'upward'; steps: number | string }
  | { type: 'watch-attr'; names: string[] }
  | { type: 'min-text-length'; length: number };

type SerializedAction =
  | { type: 'hide' }
  | { type: 'uncheck' }
  | { type: 'click-dismiss' }
  | { type: 'unlock-scroll' }
  | { type: 'remove' }
  | { type: 'remove-attr'; pattern: string | SerializedRegex }
  | { type: 'remove-class'; pattern: string | SerializedRegex }
  | { type: 'style'; decls: Array<[string, string]> };

interface SerializedRule {
  ruleId: number;
  hosts: string[];
  entity: boolean;
  pathRe: SerializedRegex | null;
  selector: string;
  procedural: SerializedProcOp[];
  action: SerializedAction;
}

function reviveRegex(value: string | SerializedRegex): string | RegExp {
  if (typeof value === 'string') {
    return value;
  }
  return new RegExp(value.source, value.flags);
}

function reviveProcOp(op: SerializedProcOp): ProcOp {
  switch (op.type) {
    case 'has-text':
      return { type: 'has-text', needle: reviveRegex(op.needle) };
    case 'matches-path':
      return { type: 'matches-path', pattern: reviveRegex(op.pattern) };
    case 'matches-attr':
      return {
        type: 'matches-attr',
        name: op.name,
        value: op.value === undefined ? undefined : reviveRegex(op.value),
      };
    case 'matches-css':
      return {
        type: 'matches-css',
        property: op.property,
        value: reviveRegex(op.value),
      };
    case 'upward':
      return { type: 'upward', steps: op.steps };
    case 'watch-attr':
      return { type: 'watch-attr', names: op.names };
    case 'min-text-length':
      return { type: 'min-text-length', length: op.length };
    default:
      return { type: 'watch-attr', names: [] };
  }
}

function reviveAction(action: SerializedAction): CompiledProc['action'] {
  switch (action.type) {
    case 'remove-attr':
      return { type: 'remove-attr', pattern: reviveRegex(action.pattern) };
    case 'remove-class':
      return { type: 'remove-class', pattern: reviveRegex(action.pattern) };
    default:
      return action;
  }
}

export function revivePackagedRules(): CompiledProc[] {
  return (SERIALIZED as SerializedRule[]).map((row) => ({
    ruleId: row.ruleId,
    hosts: row.hosts,
    entity: row.entity,
    pathRe: row.pathRe ? new RegExp(row.pathRe.source, row.pathRe.flags) : null,
    selector: row.selector,
    procedural: row.procedural.map(reviveProcOp),
    action: reviveAction(row.action),
  }));
}
`;

writeFileSync(resolve(root, 'src/content/packaged-rules.ts'), out, 'utf8');
console.log(
  `Wrote cosmetic-boot.css (${bootCompiled.genericCss.length} bytes), dist/packaged-host-css.json (${Object.keys(hostCss).length} hosts), ${procedural.length} procedural rules`,
);
